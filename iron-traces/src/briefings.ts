export const chineseCount = (text: string) =>
  (text.match(/\p{Script=Han}/gu) ?? []).length;
export function historyMarkup(idOrIndex: string | number = 0) {
  const b = (typeof idOrIndex === "number" ? BRIEFINGS[idOrIndex] : BRIEFINGS.find((briefing) => briefing.id === idOrIndex)) ?? BRIEFINGS[0],
    count = chineseCount(b.sections.map((s) => s.text).join(""));
  const readingSections = [b.sections[4], ...b.sections.slice(0, 4)];
  return `<div class="history-heading"><div><span class="dossier-kicker">战史阅读 / HISTORICAL CONTEXT</span><h2>${b.title}</h2></div><div class="reading-tools"><span>${count} 字 · 约 5 分钟</span><button id="autoRead" aria-pressed="false">自动滚动</button><span id="readProgress">0%</span></div></div>
 <nav class="history-chapters" aria-label="战史章节">${readingSections.map((s, i) => `<button data-chapter="${i}">${s.title.split(" · ")[1]}</button>`).join("")}</nav>
 <div id="historyReader" class="history-reader" tabindex="0" role="region" aria-label="完整战役背景，可滚动阅读">${readingSections.map((s, i) => `<section id="history-${i}"><h3>${s.title.startsWith("05") ? "行动命令" : s.title}</h3><p>${s.text}</p><small>${b.sources[s.source].url ? `参考：<a href="${b.sources[s.source].url}" target="_blank" rel="noopener">${b.sources[s.source].label}</a>` : b.sources[s.source].label}</small></section>`).join("")}<p class="history-end">战史资料到此。局部任务与车组为游戏改编。</p></div>`;
}
